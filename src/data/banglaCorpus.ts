const segmenter =
  typeof Intl !== 'undefined' && 'Segmenter' in Intl
    ? new Intl.Segmenter('bn', { granularity: 'grapheme' })
    : null;

export function splitGraphemes(word: string): GraphemeToken[] {
  if (!segmenter) {
    return Array.from(word).map((ch) => ({
      grapheme: ch,
      codepoints: Array.from(ch),
    }));
  }
  const tokens: GraphemeToken[] = [];
  for (const seg of segmenter.segment(word)) {
    tokens.push({
      grapheme: seg.segment,
      codepoints: Array.from(seg.segment),
    });
  }
  return tokens;
}

export function tokenizeWords(text: string): WordToken[] {
  const rawWords = text
    .trim()
    .split(/\s+/)
    .filter((w) => w.length > 0);
  return rawWords.map((word) => {
    const clusters = splitGraphemes(word);
    return {
      word,
      clusters,
      codepoints: Array.from(word),
    };
  });
}
